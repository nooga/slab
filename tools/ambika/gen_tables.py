#!/usr/bin/env python3
"""Pack the Ambika voicecard's lookup tables into one asset.

Usage: gen_tables.py PATH/TO/ambika-checkout

Reads voicecard/resources.cc and controller/resources.cc of
https://github.com/pichenettes/ambika (GPL-3.0-or-later, Emilie Gillet) and
writes
  machines/ambika/assets/tables.wav          one float32 mono WAV of the tables
  kernels/06-voices/ambika_tables.fy         the offsets of each, as constants

Values are the firmware's integers, unscaled: the kernel reads them with f@i
and does the firmware's arithmetic.
"""
import re, struct, sys, pathlib

root = pathlib.Path(sys.argv[1])
out = pathlib.Path(__file__).resolve().parents[2]


def arrays(path):
    text = path.read_text()
    found = {}
    for m in re.finditer(r"const prog_u?int(?:8|16)_t (\w+)\[\] PROGMEM = \{(.*?)\};", text, re.S):
        found[m.group(1)] = [int(v) for v in re.findall(r"-?\d+", m.group(2))]
    return found


vc = arrays(root / "voicecard/resources.cc")
ct = arrays(root / "controller/resources.cc")

tables = []  # (constant, values)


def add(name, vals):
    tables.append((name, [float(v) for v in vals]))


add("AMB-LFO-INC", vc["lut_res_lfo_increments"])
add("AMB-ENV-INC", vc["lut_res_env_portamento_increments"])
add("AMB-OSC-INC", vc["lut_res_oscillator_increments"])
add("AMB-FM-RATIO", vc["lut_res_fm_frequency_ratios"])
add("AMB-CZ-RESET", vc["lut_res_cz_phase_reset"])
# The firmware's waveform_table[2..23], 257 samples each, so that its index
# arithmetic works unchanged: slot 0 sine, 1+z square, 8+z saw, 15+z triangle
# for zone z in 0..6 [zone 6 is the sine again; the triangle shares zone 0's
# table for zones 1 and 2].
tri = {0: 0, 1: 0, 2: 0, 3: 3, 4: 4, 5: 5}
slots = [vc["wav_res_sine"]]
slots += [vc[f"wav_res_bandlimited_square_{k}"] for k in range(6)] + [vc["wav_res_sine"]]
slots += [vc[f"wav_res_bandlimited_saw_{k}"] for k in range(6)] + [vc["wav_res_sine"]]
slots += [vc[f"wav_res_bandlimited_triangle_{tri[k]}"] for k in range(6)] + [vc["wav_res_sine"]]
add("AMB-WTAB", [v for sl in slots for v in sl])
add("AMB-FORMANT-SINE", vc["wav_res_formant_sine"])
add("AMB-FORMANT-SQUARE", vc["wav_res_formant_square"])
add("AMB-VOWEL", vc["wav_res_vowel_data"])
add("AMB-DISTORTION", vc["wav_res_distortion"])
add("AMB-ENV-EXPO", vc["wav_res_env_expo"])
add("AMB-WAVES", vc["wav_res_waves"])
add("AMB-WAVETABLES", vc["wav_res_wavetables"])
add("AMB-LFO-WAVES", ct["wav_res_lfo_waveforms"])

data = []
consts = []
for name, vals in tables:
    consts.append((name, len(data), len(vals)))
    data.extend(vals)

pcm = struct.pack(f"<{len(data)}f", *data)
hdr = b"RIFF" + struct.pack("<I", 36 + len(pcm)) + b"WAVE"
hdr += b"fmt " + struct.pack("<IHHIIHH", 16, 3, 1, 48000, 48000 * 4, 4, 32)
hdr += b"data" + struct.pack("<I", len(pcm))
(out / "machines/ambika/assets/tables.wav").write_bytes(hdr + pcm)

lines = [
    "( ambika_tables.fy - offsets into machines/ambika/assets/tables.wav.",
    "",
    "  Generated by tools/ambika/gen_tables.py from the Ambika firmware's",
    "  resources [Emilie Gillet, GPL-3.0-or-later].  Do not edit; each constant",
    "  is the first sample of a table, the comment its length. )",
    "",
]
for name, off, n in consts:
    lines.append(f":: {name} {off}.0 ;  ( {n} )")
(out / "kernels/06-voices/ambika_tables.fy").write_text("\n".join(lines) + "\n")
print(len(data), "values;", len(pcm) // 1024, "KiB")
for c in consts:
    print(*c)
