#!/usr/bin/env python3
"""Write kernels/10-physical/bessel.fy: the circular membrane's first 40
modes (docs/41) - Bessel-zero ratios j_mn/j_01, nodal diameters m, and the
radial shapes J_m(j_mn r) at 17 radii, peak-normalized.

    python3 tools/fit/bessel.py            # rewrites the .fy next to it

J_m comes from its integral form, the zeros from bisection; numpy only.
"""
import os
import numpy as np

N_MODES = 40
RADII = 17
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "kernels", "10-physical", "bessel.fy")


def J(m, x):
    t = np.linspace(0, np.pi, 4001)
    return np.trapezoid(np.cos(m * t[None, :] - np.outer(np.atleast_1d(x), np.sin(t))), t, axis=1) / np.pi


def zeros_of(m, count=6, top=40.0):
    xs = np.linspace(max(0.1, m), top, 40000)
    v = J(m, xs)
    out = []
    for i in np.where(np.sign(v[:-1]) != np.sign(v[1:]))[0][:count]:
        a, b = xs[i], xs[i + 1]
        for _ in range(50):
            c = (a + b) / 2
            if np.sign(J(m, a)[0]) == np.sign(J(m, c)[0]):
                a = c
            else:
                b = c
        out.append(a)
    return out


def lst(vals, scale, per):
    ints = [int(round(v * scale)) for v in vals]
    return "\n        ".join(" ".join(str(x) for x in ints[i:i + per]) for i in range(0, len(ints), per))


def main():
    modes = sorted((z, m) for m in range(12) for z in zeros_of(m))[:N_MODES]
    z = np.array([q for q, _ in modes])
    m = [mm for _, mm in modes]
    rs = np.linspace(0, 1, RADII)
    shapes = []
    for q, mm in modes:
        peak = np.abs(J(mm, q * np.linspace(0, 1, 400))).max()
        shapes.append(J(mm, q * rs) / peak)
    flat = list(np.array(shapes).reshape(-1)) + [shapes[-1][-1]]
    ratio = list(z / z[0]) + [z[-1] / z[0]]
    text = f"""( bessel.fy - the ideal circular membrane's first 40 modes [docs/41].

  A membrane of radius a under uniform tension, fixed at the rim, has
  modes J_m[j_mn r/a] cos[m theta] at f_mn = j_mn c / [2 pi a], where j_mn
  is the n-th zero of the Bessel function J_m [Rayleigh, Theory of Sound,
  ch. 9; Fletcher and Rossing, The Physics of Musical Instruments, 3.6].
  The tables hold the 40 lowest, sorted by frequency: the ratio to the
  fundamental j_01 = 2.4048, the nodal diameters m, and each mode's
  radial shape at 17 radii r/a = 0, 1/16 .. 1, normalized to a peak of 1.
  Generated by tools/fit/bessel.py; don't edit by hand.

  memb-shape-at [mode r -- y] reads the shape at r in 0..1 by linear
  interpolation; strike points and microphone points use it. )

include "../00-primitives/table.fy"

:: MEMB-N {N_MODES} ;

( j_mn / j_01, x 1e6 )
table: memb-ratio {N_MODES}
  f>i [ {lst(ratio, 1000000, 10)} ] swap qnth i>f 0.000001 f* ;

( nodal diameters m )
table: memb-m {N_MODES}
  f>i [ {lst(m + [m[-1]], 1, 20)} ] swap qnth i>f ;

( J_m[j_mn r] / max |J_m|, mode-major, {RADII} radii per mode, x 1e6 )
table: memb-shape {N_MODES * RADII}
  f>i [ {lst(flat, 1000000, RADII)} ] swap qnth i>f 0.000001 f* ;

( mode r -- y : mode i's radial shape at r in [0, 1], interpolated )
dsp: memb-shape-at | i r -- y |
  r 0.0 1.0 fclamp 16.0 f* | x |
  x floor 15.0 fmin | x0 |
  x x0 f- | fr |
  i 17.0 f* x0 f+ | j |
  memb-shape j f@i | a |
  memb-shape j 1.0 f+ f@i | b |
  a  b a f- fr f*  f+
;
"""
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
